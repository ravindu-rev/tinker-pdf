/// The plaintext behind `LZW_EARLY1`/`LZW_EARLY0`: three 256-byte rows, long
/// enough that the table crosses code 511 where the two settings diverge.
fn lzw_source() -> Vec<u8> {
    let mut v: Vec<u8> = (0..=255u8).collect();
    v.extend((0..256u32).map(|i| ((i * 3) % 256) as u8));
    v.extend(core::iter::repeat_n(0u8, 128));
    v.extend((100..228u32).map(|x| x as u8));
    v
}

#[test]
fn lzw_early_change_one_and_zero_are_both_pinned() {
    let src = lzw_source();
    let d = lzw_decode(LZW_EARLY1, &CAP, true, None).expect("no predictor");
    assert_eq!(d.data, src);
    assert!(d.complete);
    assert!(d.warnings.is_empty());

    let d = lzw_decode(LZW_EARLY0, &CAP, false, None).expect("no predictor");
    assert_eq!(d.data, src);
    assert!(d.complete);
    assert!(d.warnings.is_empty());

    // The settings are not interchangeable: reading either stream with the
    // other setting must not silently produce the same bytes.
    let wrong = lzw_decode(LZW_EARLY1, &CAP, false, None).expect("no predictor");
    assert_ne!(wrong.data, src);
    let wrong = lzw_decode(LZW_EARLY0, &CAP, true, None).expect("no predictor");
    assert_ne!(wrong.data, src);
}

