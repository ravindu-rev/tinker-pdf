#[test]
fn output_cap_truncates_an_expanding_stream() {
    // 29 bytes of zlib expanding to 5000; the cap stops it mid-copy.
    let d = flate_decode(ZLIB_BIG_A, &Limits::new(100), None).expect("no predictor");
    assert_eq!(d.data.len(), 100);
    assert!(d.data.iter().all(|&b| b == b'A'));
    assert!(!d.complete);
    assert!(d.warnings.contains(&Warning::OutputCapHit));

    let d = flate(ZLIB_BIG_A);
    assert_eq!(d.data.len(), 5000);
    assert!(d.complete);
}

