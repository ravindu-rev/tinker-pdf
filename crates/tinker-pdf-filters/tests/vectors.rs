#[test]
fn raw_deflate_block_types() {
    for (name, bytes, plain) in [
        ("stored", DEFLATE_STORED, HELLO),
        ("fixed", DEFLATE_FIXED, HELLO),
        ("dynamic", DEFLATE_DYNAMIC, LONG_TEXT),
    ] {
        let d = flate(bytes);
        assert_eq!(d.data, plain, "{name}");
        assert!(d.complete, "{name}: {:?}", d.warnings);
        // Raw deflate under a FlateDecode name is the documented fallback.
        assert_eq!(d.warnings, vec![Warning::RawDeflateFallback], "{name}");
    }
}

