/// The subset of PostScript a CMap resource actually uses.
#[derive(Debug, PartialEq, Eq)]
enum Token {
    Hex(Vec<u8>),
    Name(String),
    Number(i64),
    Keyword(String),
}

/// Reads one vendored CMap.
///
/// `notdefrange` is deliberately not read. It names the CID to substitute for
/// a code that is inside a codespace and mapped by nothing, which in every
/// vendored CMap is the collection's space or notdef glyph -- so honouring it
/// would replace "this code means nothing" with a guess that happens to look
/// like a real answer. Leaving those codes unmapped is the same choice this
/// gap makes everywhere else.
fn parse(bytes: &[u8], name: &str) -> Cmap {
    let mut cmap = Cmap::default();
    let mut tokens = Tokenizer { bytes, pos: 0 };
    let mut stack: Vec<Token> = Vec::new();

    while let Some(token) = tokens.next_token() {
        let Token::Keyword(word) = &token else {
            stack.push(token);
            if stack.len() > 4 {
                stack.remove(0);
            }
            continue;
        };
        match word.as_str() {
            "begincodespacerange" => {
                for record in section(&mut tokens, "endcodespacerange", 2, name) {
                    let (Token::Hex(low), Token::Hex(high)) = (&record[0], &record[1]) else {
                        panic!("{name}: a codespace range that is not two hex strings");
                    };
                    let width = low.len();
                    assert!(
                        (1..=4).contains(&width) && high.len() == width,
                        "{name}: a codespace range whose bounds are {width} and {} bytes",
                        high.len()
                    );
                    cmap.codespaces.push((width as u8, be(low), be(high)));
                }
            }
            "begincidrange" => {
                for record in section(&mut tokens, "endcidrange", 3, name) {
                    let (Token::Hex(low), Token::Hex(high), Token::Number(cid)) =
                        (&record[0], &record[1], &record[2])
                    else {
                        panic!("{name}: a cidrange that is not <low> <high> cid");
                    };
                    cmap.ranges.push((
                        be(low),
                        be(high),
                        u32::try_from(*cid).expect("a CID is not negative"),
                    ));
                }
            }
            "begincidchar" => {
                for record in section(&mut tokens, "endcidchar", 2, name) {
                    let (Token::Hex(code), Token::Number(cid)) = (&record[0], &record[1]) else {
                        panic!("{name}: a cidchar that is not <code> cid");
                    };
                    cmap.ranges.push((
                        be(code),
                        be(code),
                        u32::try_from(*cid).expect("a CID is not negative"),
                    ));
                }
            }
            "beginnotdefrange" => {
                let _ = section(&mut tokens, "endnotdefrange", 3, name);
            }
            "usecmap" => {
                if let Some(Token::Name(parent)) = stack.last() {
                    cmap.parent = Some(parent.clone());
                }
                stack.clear();
            }
            "def" => {
                if let (Some(Token::Number(n)), Some(Token::Name(key))) =
                    (stack.last(), stack.get(stack.len().wrapping_sub(2)))
                {
                    if key == "WMode" {
                        cmap.vertical = *n == 1;
                        cmap.wmode_declared = true;
                    }
                }
                stack.clear();
            }
            _ => stack.clear(),
        }
    }

    assert!(
        !cmap.codespaces.is_empty() || cmap.parent.is_some(),
        "{name}: no codespace ranges and no usecmap, so it can split nothing"
    );
    cmap
}

/// Reads records of `width` tokens until `end`.
fn section(tokens: &mut Tokenizer, end: &str, width: usize, name: &str) -> Vec<Vec<Token>> {
    let mut out = Vec::new();
    let mut record = Vec::new();
    loop {
        let token = tokens
            .next_token()
            .unwrap_or_else(|| panic!("{name}: input ended inside a section wanting {end}"));
        if token == Token::Keyword(end.to_string()) {
            assert!(record.is_empty(), "{name}: {end} in the middle of a record");
            return out;
        }
        record.push(token);
        if record.len() == width {
            out.push(std::mem::take(&mut record));
        }
    }
}

fn be(bytes: &[u8]) -> u32 {
    bytes.iter().fold(0u32, |a, &b| (a << 8) | u32::from(b))
}

struct Tokenizer<'a> {
    bytes: &'a [u8],
    pos: usize,
}

impl Tokenizer<'_> {
    fn next_token(&mut self) -> Option<Token> {
        loop {
            let b = *self.bytes.get(self.pos)?;
            if b.is_ascii_whitespace() {
                self.pos += 1;
                continue;
            }
            // Every vendored file opens with forty lines of `%%Copyright`.
            if b == b'%' {
                while self
                    .bytes
                    .get(self.pos)
                    .is_some_and(|&c| c != b'\n' && c != b'\r')
                {
                    self.pos += 1;
                }
                continue;
            }
            break;
        }

        let b = *self.bytes.get(self.pos)?;
        match b {
            b'<' => {
                self.pos += 1;
                let start = self.pos;
                while self.bytes.get(self.pos).is_some_and(|&c| c != b'>') {
                    self.pos += 1;
                }
                let text = &self.bytes[start..self.pos];
                self.pos += 1;
                let digits: Vec<u8> = text
                    .iter()
                    .filter(|c| !c.is_ascii_whitespace())
                    .copied()
                    .collect();
                assert!(
                    digits.len() % 2 == 0 && digits.iter().all(u8::is_ascii_hexdigit),
                    "a hex string with an odd or non-hex body"
                );
                Some(Token::Hex(
                    digits
                        .chunks_exact(2)
                        .map(|p| {
                            let hi = (p[0] as char).to_digit(16).expect("checked above") as u8;
                            let lo = (p[1] as char).to_digit(16).expect("checked above") as u8;
                            (hi << 4) | lo
                        })
                        .collect(),
                ))
            }
            b'/' => {
                self.pos += 1;
                Some(Token::Name(self.word()))
            }
            b'0'..=b'9' | b'-' | b'+' | b'.' => {
                let word = self.word();
                // `/CMapVersion 11.006 def` is a real number and nothing reads
                // it; only the integers matter.
                Some(Token::Number(word.parse::<i64>().unwrap_or(0)))
            }
            b'[' | b']' | b'(' | b')' | b'{' | b'}' => {
                self.pos += 1;
                Some(Token::Keyword(String::from(b as char)))
            }
            _ => Some(Token::Keyword(self.word())),
        }
    }

    /// Bytes up to the next delimiter or space.
    fn word(&mut self) -> String {
        let start = self.pos;
        while self.bytes.get(self.pos).is_some_and(|&c| {
            !c.is_ascii_whitespace()
                && !matches!(
                    c,
                    b'(' | b')' | b'<' | b'>' | b'[' | b']' | b'{' | b'}' | b'/' | b'%'
                )
        }) {
            self.pos += 1;
        }
        if self.pos == start {
            self.pos += 1;
        }
        String::from_utf8_lossy(&self.bytes[start..self.pos]).into_owned()
    }
}
